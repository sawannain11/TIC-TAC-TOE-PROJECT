// what is dom
// dom is a document object model
// it is a programming interface for html and xml document.
// it represent the page so that program can change the document structure , style and content.
// dom provide a structured representation of the document as a tree of object.
// it define the way in which the document can be accessed and manipulated.
// without dom , javascript can not access the html element and change there content and style.
// why dom is important
// dom is important because it allow us to create dynamic and interactive web page.
// with the help of dom , we can change the content and style of the web page without reloading the page.
// .what is html dom
// html dom is a standard for how to get , change , add and delete html element.
// it provide a way to access and manipulate the html document as a tree of object.
// the html dom represent the page so that program can change the document structure , style and content.
// what is dom tree
// the dom tree is a hierarchical representation of the html document.
// it represent the document as a tree of object where each node is an object representing an html element.
// what is bom
// the bom is a browser object model
// it is a programming interface for web browser.
// window object is the top level object in the bom hierarchy.
// it represent the browser window and provide method and properties to interact with the browser.
// the bom provide access to the browser features such as history , location , navigator and screen.
